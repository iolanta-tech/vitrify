//! The command-line definition and the documentation model derived from it.

use std::process::ExitCode;

use clap::{Arg, Command, CommandFactory, Parser, Subcommand};
use serde_json::{Map, Value, json};

use crate::context::OutputFormat;
use crate::{context, sparql};

const MODEL_COMMENT: &str = "# Generated by `j cli-model`. Do not edit.\n";

#[derive(Parser)]
#[command(
    name = "vitrify",
    version,
    about = "Record a remote retrieval with metadata and provenance"
)]
struct Cli {
    #[command(subcommand)]
    command: SubcommandName,
}

#[derive(Subcommand)]
enum SubcommandName {
    /// Execute a SPARQL query and write the response to a file.
    Sparql(SparqlArgs),
    /// Fetch a JSON-LD or YAML-LD context and print it with retrieval metadata.
    Context(ContextArgs),
    /// Print the CLI model and exit.
    #[command(hide = true, name = "cli-model")]
    CliModel,
}

#[derive(clap::Args)]
struct SparqlArgs {
    /// SPARQL endpoint URL.
    #[arg(long, value_name = "IRI")]
    endpoint: String,
    /// Query file path, or `-` to read the query from standard input.
    #[arg(long, value_name = "PATH")]
    query: String,
    /// Output directory for the result and its RO-Crate.
    #[arg(long, value_name = "DIRECTORY")]
    to: std::path::PathBuf,
    /// Requested result format. Omit it to accept the endpoint choice.
    #[arg(long, value_name = "FORMAT")]
    format: Option<String>,
}

#[derive(clap::Args)]
struct ContextArgs {
    /// Absolute HTTP(S) URL of the context.
    #[arg(value_name = "URL")]
    url: String,
    /// Serialization of the printed document. jsonld is the default.
    #[arg(long = "as", value_enum, default_value = "jsonld")]
    output: ContextOutput,
}

#[derive(Clone, Copy, clap::ValueEnum)]
enum ContextOutput {
    Jsonld,
    Yamlld,
}

pub fn execute() -> ExitCode {
    let result = match Cli::parse().command {
        SubcommandName::CliModel => {
            print!("{}", model());
            return ExitCode::SUCCESS;
        }
        SubcommandName::Sparql(args) => sparql(
            &args.endpoint,
            &args.query,
            args.format.as_deref(),
            &args.to,
        ),
        SubcommandName::Context(args) => {
            let format = match args.output {
                ContextOutput::Jsonld => OutputFormat::JsonLd,
                ContextOutput::Yamlld => OutputFormat::YamlLd,
            };
            context(&args.url, format).map(|document| print!("{document}"))
        }
    };
    match result {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("error: {error}");
            ExitCode::FAILURE
        }
    }
}

pub fn model() -> String {
    let yaml =
        crate::yaml::to_string(&document(&Cli::command())).expect("CLI model must serialize");
    let body = unquote_values(
        yaml.strip_prefix("---\n")
            .unwrap_or(yaml.as_str())
            .trim_start_matches('\n'),
    );
    format!("{MODEL_COMMENT}{body}")
}

fn unquote_values(yaml: &str) -> String {
    let mut text = yaml
        .lines()
        .map(unquote_value)
        .collect::<Vec<_>>()
        .join("\n");
    text.push('\n');
    text
}

fn unquote_value(line: &str) -> String {
    let Some((head, quoted)) = line.split_once(": \"") else {
        return line.to_owned();
    };
    let Some(value) = quoted.strip_suffix('"') else {
        return line.to_owned();
    };
    if needs_quotes(value) {
        return line.to_owned();
    }
    format!("{head}: {value}")
}

fn needs_quotes(value: &str) -> bool {
    value.contains(": ")
        || value.contains(" #")
        || (value.starts_with('-') && !value.starts_with("--"))
        || value.starts_with([
            '?', ':', ',', '[', ']', '{', '}', '#', '&', '*', '!', '|', '>', '\'', '"', '%', '@',
            '`',
        ])
}

fn document(command: &Command) -> Value {
    let mut node = Map::new();
    node.insert("@context".to_owned(), json!("urn:vitrify:cli"));
    node.insert("@graph".to_owned(), Value::Array(commands(command)));
    Value::Object(node)
}

fn commands(root: &Command) -> Vec<Value> {
    root.get_subcommands()
        .filter(|command| !command.is_hide_set())
        .enumerate()
        .map(|(index, command)| command_node(command, index + 1))
        .collect()
}

fn command_node(command: &Command, position: usize) -> Value {
    let name = command.get_name();
    let mut node = Map::new();
    node.insert("$id".to_owned(), json!(format!("urn:vitrify:cli:{name}")));
    node.insert("$type".to_owned(), json!("cwl:CommandLineTool"));
    node.insert("name".to_owned(), json!(name));
    node.insert("order".to_owned(), json!(position));
    node.insert("comment".to_owned(), json!(plain(command.get_about())));
    node.insert("inputs".to_owned(), Value::Array(arguments(command, name)));
    Value::Object(node)
}

fn arguments(command: &Command, command_name: &str) -> Vec<Value> {
    command
        .get_arguments()
        .filter(|arg| !arg.is_hide_set())
        .filter(|arg| arg.get_id() != "help" && arg.get_id() != "version")
        .enumerate()
        .map(|(index, arg)| argument_node(arg, command_name, index + 1))
        .collect()
}

fn argument_node(arg: &Arg, command_name: &str, position: usize) -> Value {
    let token = arg.get_long().unwrap_or(arg.get_id().as_str());
    let mut node = Map::new();
    node.insert(
        "$id".to_owned(),
        json!(format!("urn:vitrify:cli:{command_name}:{token}")),
    );
    node.insert("$type".to_owned(), json!("cwl:CommandInputParameter"));
    node.insert("name".to_owned(), json!(token));
    node.insert("usage".to_owned(), json!(usage(arg)));
    node.insert("order".to_owned(), json!(position));
    node.insert("valueRequired".to_owned(), json!(arg.is_required_set()));
    node.insert("comment".to_owned(), json!(plain(arg.get_help())));
    if let Some(long) = arg.get_long() {
        let mut binding = Map::new();
        binding.insert("$type".to_owned(), json!("cwl:CommandLineBinding"));
        binding.insert("prefix".to_owned(), json!(format!("--{long}")));
        node.insert("inputBinding".to_owned(), Value::Object(binding));
    }
    Value::Object(node)
}

fn usage(arg: &Arg) -> String {
    let possible = arg.get_possible_values();
    let values: Vec<&str> = possible
        .iter()
        .filter(|value| !value.is_hide_set())
        .map(|value| value.get_name())
        .collect();
    if let Some(long) = arg.get_long() {
        if values.is_empty() {
            return named_option(long, arg);
        }
        return values
            .iter()
            .map(|value| format!("--{long} {value}"))
            .collect::<Vec<_>>()
            .join(" or ");
    }
    value_name(arg).unwrap_or_else(|| arg.get_id().to_string())
}

fn named_option(long: &str, arg: &Arg) -> String {
    match value_name(arg) {
        Some(name) => format!("--{long} {name}"),
        None => format!("--{long}"),
    }
}

fn value_name(arg: &Arg) -> Option<String> {
    arg.get_value_names()
        .and_then(|names| names.first())
        .map(|name| name.to_string())
}

fn plain(text: Option<&clap::builder::StyledStr>) -> String {
    let words = text
        .map(ToString::to_string)
        .unwrap_or_default()
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ");
    if words.is_empty() || words.ends_with(['.', '!', '?']) {
        return words;
    }
    format!("{words}.")
}

#[cfg(test)]
mod tests {
    use clap::CommandFactory;

    use super::*;

    #[test]
    fn model_flag_is_hidden_and_accepted_without_a_subcommand() {
        let mut command = Cli::command();
        assert!(!command.render_help().to_string().contains("cli-model"));
        command
            .try_get_matches_from(["vitrify", "cli-model"])
            .unwrap();
    }

    #[test]
    fn model_records_the_public_arguments() {
        let value: Value = crate::yaml::from_str(&model()).unwrap();
        let commands = value["@graph"].as_array().unwrap();
        assert_eq!(commands[0]["name"], "sparql");
        assert_eq!(commands[0]["$type"], "cwl:CommandLineTool");
        assert_eq!(commands[1]["name"], "context");
        let sparql_usage: Vec<_> = commands[0]["inputs"]
            .as_array()
            .unwrap()
            .iter()
            .map(|argument| argument["usage"].as_str().unwrap())
            .collect();
        assert_eq!(
            sparql_usage,
            [
                "--endpoint IRI",
                "--query PATH",
                "--to DIRECTORY",
                "--format FORMAT"
            ]
        );
        let context_args = commands[1]["inputs"].as_array().unwrap();
        assert_eq!(context_args[0]["usage"], "URL");
        assert_eq!(context_args[0]["valueRequired"], true);
        assert_eq!(context_args[1]["usage"], "--as jsonld or --as yamlld");
        assert_eq!(context_args[1]["valueRequired"], false);
        assert_eq!(context_args[1]["inputBinding"]["prefix"], "--as");
        let names: Vec<_> = commands
            .iter()
            .map(|command| command["name"].as_str().unwrap())
            .collect();
        assert_eq!(names, ["sparql", "context"]);
    }
}
